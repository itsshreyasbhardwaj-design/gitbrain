import { describe, expect, it } from 'vitest';

import type { DependencyReport, EntryPoint, ModuleGraph } from '../types';
import { makeSnapshot } from '../testing/fixtures';
import { buildModuleGraph, packageRoot } from './build';

function makeDeps(names: readonly string[] = []): DependencyReport {
  return {
    dependencies: names.map((name) => ({
      name,
      range: '^1.0.0',
      kind: 'runtime' as const,
      manifest: 'package.json',
      ecosystem: 'npm',
    })),
    manifests: names.length > 0 ? ['package.json'] : [],
    counts: { runtime: names.length, dev: 0, peer: 0, optional: 0 },
    flagged: [],
    unpinned: [],
    hasLockfile: true,
  };
}

function entry(path: string): EntryPoint {
  return { path, reason: 'test fixture', kind: 'app', confidence: 'high' };
}

function build(
  files: Record<string, string>,
  options: { deps?: readonly string[]; entries?: readonly EntryPoint[] } = {},
): ModuleGraph {
  return buildModuleGraph(makeSnapshot(files), makeDeps(options.deps ?? []), options.entries ?? []);
}

function edgeKeys(graph: ModuleGraph): string[] {
  return graph.edges.map((edge) => `${edge.from}->${edge.to}`).sort();
}

describe('buildModuleGraph — nodes and edges', () => {
  it('creates one node per source file and an edge per resolved import', () => {
    const graph = build({
      'src/index.ts': `import { format } from './format';\nexport const run = () => format();`,
      'src/format.ts': `export const format = () => 'x';`,
      'README.md': '# not a source file',
      'src/logo.svg': '<svg />',
    });

    expect(graph.nodes.map((node) => node.id).sort()).toEqual(['src/format.ts', 'src/index.ts']);
    expect(edgeKeys(graph)).toEqual(['src/index.ts->src/format.ts']);
    expect(graph.edges[0]?.specifier).toBe('./format');
  });

  it('labels nodes by basename and carries language and line counts', () => {
    const graph = build({ 'src/deep/thing.ts': 'export const a = 1;\nexport const b = 2;\n' });

    const node = graph.nodes[0];
    expect(node?.label).toBe('thing.ts');
    expect(node?.language).toBe('TypeScript');
    expect(node?.loc).toBe(3);
  });

  it('drops self-edges and deduplicates repeated imports of the same target', () => {
    const graph = build({
      'src/a.ts': [
        `import './a';`,
        `import { x } from './b';`,
        `import { y } from './b';`,
        `const lazy = () => import('./b');`,
      ].join('\n'),
      'src/b.ts': 'export const x = 1;\nexport const y = 2;',
    });

    expect(edgeKeys(graph)).toEqual(['src/a.ts->src/b.ts']);
  });

  it('ignores imports that resolve to non-source assets', () => {
    const graph = build({
      'src/a.ts': `import data from './data.json';`,
      'src/data.json': '{}',
    });

    expect(graph.edges).toEqual([]);
    expect(graph.externals).toEqual([]);
  });

  it('excludes generated and vendored files from the graph', () => {
    const graph = build({
      'src/a.ts': `import './b';`,
      'src/b.ts': '// @generated by codegen\nexport const b = 1;',
      'vendor/lib/c.ts': 'export const c = 1;',
    });

    expect(graph.nodes.map((node) => node.id)).toEqual(['src/a.ts']);
    expect(graph.edges).toEqual([]);
  });

  it('resolves imports through a tsconfig @/* alias found in the snapshot', () => {
    const graph = build({
      'tsconfig.json': `{
        // Editor and bundler share this map.
        "compilerOptions": { "paths": { "@/*": ["./src/*"] } },
      }`,
      'src/app/page.tsx': `import { format } from '@/lib/format';\nexport default function Page() { return format(); }`,
      'src/lib/format.ts': `export const format = () => 'x';`,
    });

    expect(edgeKeys(graph)).toEqual(['src/app/page.tsx->src/lib/format.ts']);
    expect(graph.externals).toEqual([]);
  });

  it('rebases aliases onto the directory of the tsconfig that declared them', () => {
    const graph = build({
      'apps/web/tsconfig.json': `{"compilerOptions":{"paths":{"@/*":["./src/*"]}}}`,
      'apps/web/src/page.ts': `import { x } from '@/lib/x';`,
      'apps/web/src/lib/x.ts': 'export const x = 1;',
    });

    expect(edgeKeys(graph)).toEqual(['apps/web/src/page.ts->apps/web/src/lib/x.ts']);
  });
});

describe('buildModuleGraph — degrees and instability', () => {
  it('computes in/out degrees and I = out / (in + out)', () => {
    const graph = build({
      'src/entry.ts': `import './middle';`,
      'src/middle.ts': `import './leaf';\nexport const m = 1;`,
      'src/leaf.ts': 'export const l = 1;',
    });

    const byId = new Map(graph.nodes.map((node) => [node.id, node]));

    expect(byId.get('src/entry.ts')).toMatchObject({ inDegree: 0, outDegree: 1, instability: 1 });
    expect(byId.get('src/middle.ts')).toMatchObject({
      inDegree: 1,
      outDegree: 1,
      instability: 0.5,
    });
    expect(byId.get('src/leaf.ts')).toMatchObject({ inDegree: 1, outDegree: 0, instability: 0 });
  });

  it('reports instability 0 for a fully isolated node rather than NaN', () => {
    const graph = build({ 'src/alone.ts': 'export const a = 1;' });
    expect(graph.nodes[0]?.instability).toBe(0);
  });
});

describe('buildModuleGraph — cycles', () => {
  it('detects a deliberate three-node cycle and orders it as a walk', () => {
    const graph = build({
      'src/a.ts': `import './b';\nexport const a = 1;`,
      'src/b.ts': `import './c';\nexport const b = 1;`,
      'src/c.ts': `import './a';\nexport const c = 1;`,
    });

    expect(graph.cycles).toEqual([['src/a.ts', 'src/b.ts', 'src/c.ts']]);
    expect(graph.edges.every((edge) => edge.circular)).toBe(true);
  });

  it('detects a two-node A -> B -> A cycle', () => {
    const graph = build({
      'src/x.ts': `import './y';\nexport const x = 1;`,
      'src/y.ts': `import './x';\nexport const y = 1;`,
    });

    expect(graph.cycles).toEqual([['src/x.ts', 'src/y.ts']]);
    expect(graph.edges.every((edge) => edge.circular)).toBe(true);
  });

  it('leaves acyclic edges unmarked and reports no cycles', () => {
    const graph = build({
      'src/a.ts': `import './b';`,
      'src/b.ts': `import './c';\nexport const b = 1;`,
      'src/c.ts': 'export const c = 1;',
    });

    expect(graph.cycles).toEqual([]);
    expect(graph.edges.every((edge) => edge.circular)).toBe(false);
  });

  it('separates independent cycles into distinct components', () => {
    const graph = build({
      'src/a.ts': `import './b';\nexport const a = 1;`,
      'src/b.ts': `import './a';\nexport const b = 1;`,
      'src/p.ts': `import './q';\nexport const p = 1;`,
      'src/q.ts': `import './p';\nexport const q = 1;`,
      'src/free.ts': 'export const f = 1;',
    });

    const sorted = graph.cycles.map((cycle) => [...cycle].sort()).sort();
    expect(sorted).toEqual([
      ['src/a.ts', 'src/b.ts'],
      ['src/p.ts', 'src/q.ts'],
    ]);
  });

  it('marks only the edges inside a component as circular', () => {
    const graph = build({
      'src/a.ts': `import './b';\nexport const a = 1;`,
      'src/b.ts': `import './a';\nimport './leaf';\nexport const b = 1;`,
      'src/leaf.ts': 'export const l = 1;',
    });

    const circular = graph.edges.filter((edge) => edge.circular).map((edge) => edge.to);
    expect(circular.sort()).toEqual(['src/a.ts', 'src/b.ts']);
  });

  it('handles a large synthetic graph without exhausting the call stack', () => {
    // 5,000 modules in one chain closed into a single strongly-connected
    // component: the DFS is 5,000 frames deep, which a recursive Tarjan would
    // not survive on a default Node stack.
    const SIZE = 5000;
    const files: Record<string, string> = {};
    for (let i = 0; i < SIZE; i++) {
      const next = (i + 1) % SIZE;
      files[`src/m${i}.ts`] = `import './m${next}';\nexport const v${i} = ${i};`;
    }

    const graph = build(files);

    expect(graph.nodes).toHaveLength(SIZE);
    expect(graph.edges).toHaveLength(SIZE);
    expect(graph.cycles).toHaveLength(1);
    expect(graph.cycles[0]).toHaveLength(SIZE);
    expect(graph.edges.every((edge) => edge.circular)).toBe(true);
    expect(graph.orphans).toEqual([]);
  });

  it('survives a deep acyclic chain, where every component has size one', () => {
    const SIZE = 4000;
    const files: Record<string, string> = {};
    for (let i = 0; i < SIZE; i++) {
      files[`src/n${i}.ts`] =
        i === SIZE - 1
          ? `export const v${i} = ${i};`
          : `import './n${i + 1}';\nexport const v${i} = ${i};`;
    }

    const graph = build(files, { entries: [entry('src/n0.ts')] });

    expect(graph.nodes).toHaveLength(SIZE);
    expect(graph.cycles).toEqual([]);
    expect(graph.orphans).toEqual([]);
  });
});

describe('buildModuleGraph — externals', () => {
  it('aggregates unresolved bare specifiers by package root', () => {
    const graph = build(
      {
        'src/a.ts': `import merge from 'lodash/merge';\nimport pick from 'lodash/pick';`,
        'src/b.ts': `import merge from 'lodash/merge';`,
      },
      { deps: ['lodash'] },
    );

    expect(graph.externals).toEqual([
      {
        name: 'lodash',
        count: 3,
        importers: ['src/a.ts', 'src/b.ts'],
        undeclared: false,
      },
    ]);
  });

  it('keeps the scope when aggregating @scope/pkg specifiers', () => {
    const graph = build(
      { 'src/a.ts': `import { Slot } from '@radix-ui/react-slot/dist/index';` },
      { deps: ['@radix-ui/react-slot'] },
    );

    expect(graph.externals[0]?.name).toBe('@radix-ui/react-slot');
    expect(graph.externals[0]?.undeclared).toBe(false);
  });

  it('flags a package that no manifest declares', () => {
    const graph = build({ 'src/a.ts': `import axios from 'axios';` }, { deps: ['react'] });

    expect(graph.externals).toEqual([
      { name: 'axios', count: 1, importers: ['src/a.ts'], undeclared: true },
    ]);
  });

  it('never flags a runtime built-in as undeclared', () => {
    const graph = build({
      'src/a.ts': `import fs from 'node:fs';\nimport path from 'path';`,
      'app/main.py': `import os\nimport json`,
      'cmd/main.go': `package main\n\nimport "fmt"`,
    });

    for (const external of graph.externals) {
      expect(external.undeclared).toBe(false);
    }
    expect(graph.externals.map((external) => external.name).sort()).toEqual([
      'fmt',
      'fs',
      'json',
      'os',
      'path',
    ]);
  });

  it('does not report a broken relative import as an external package', () => {
    const graph = build({ 'src/a.ts': `import x from './does-not-exist';` });

    expect(graph.externals).toEqual([]);
    expect(graph.edges).toEqual([]);
  });

  it('sorts externals by usage, then by name', () => {
    const graph = build({
      'src/a.ts': `import 'zebra';\nimport 'alpha';`,
      'src/b.ts': `import 'zebra';`,
      'src/c.ts': `import 'beta';`,
    });

    expect(graph.externals.map((external) => external.name)).toEqual(['zebra', 'alpha', 'beta']);
  });
});

describe('buildModuleGraph — orphans', () => {
  it('reports unreferenced modules that are not entry points', () => {
    const graph = build(
      {
        'src/index.ts': `import './used';\nexport const run = 1;`,
        'src/used.ts': 'export const used = 1;',
        'src/dead.ts': 'export const dead = 1;',
      },
      { entries: [entry('src/index.ts')] },
    );

    expect(graph.orphans).toEqual(['src/dead.ts']);

    const byId = new Map(graph.nodes.map((node) => [node.id, node]));
    expect(byId.get('src/index.ts')?.isEntry).toBe(true);
    expect(byId.get('src/index.ts')?.isOrphan).toBe(false);
    expect(byId.get('src/dead.ts')?.isOrphan).toBe(true);
    expect(byId.get('src/used.ts')?.isOrphan).toBe(false);
  });

  it('never treats a test or config file as an orphan', () => {
    const graph = build({
      'src/thing.ts': 'export const thing = 1;',
      'src/thing.test.ts': `import { thing } from './thing';\nexport const t = thing;`,
      'vitest.config.ts': 'export default {};',
      'src/lonely.ts': 'export const lonely = 1;',
    });

    expect(graph.orphans).toEqual(['src/lonely.ts']);
  });

  it('treats every unreferenced module as an orphan when no entry points are known', () => {
    const graph = build({
      'src/a.ts': `import './b';`,
      'src/b.ts': 'export const b = 1;',
    });

    expect(graph.orphans).toEqual(['src/a.ts']);
  });
});

describe('buildModuleGraph — cross-language repositories', () => {
  it('links Python modules through relative and absolute imports', () => {
    const graph = build({
      'app/__init__.py': '',
      'app/main.py': 'from .api import routes\nfrom app import models',
      'app/models.py': 'class User: pass',
      'app/api/__init__.py': '',
      'app/api/routes.py': 'from ..models import User',
    });

    expect(edgeKeys(graph)).toEqual([
      'app/api/routes.py->app/models.py',
      'app/main.py->app/__init__.py',
      'app/main.py->app/api/__init__.py',
    ]);
  });

  it('links Go packages by directory', () => {
    const graph = build({
      'cmd/server/main.go': `package main\n\nimport (\n\t"fmt"\n\t"github.com/acme/demo/internal/store"\n)`,
      'internal/store/store.go': 'package store',
    });

    expect(edgeKeys(graph)).toEqual(['cmd/server/main.go->internal/store/store.go']);
    expect(graph.externals.map((external) => external.name)).toEqual(['fmt']);
  });
});

describe('packageRoot', () => {
  it('splits npm specifiers on / with a scope exception', () => {
    expect(packageRoot('lodash/merge', 'ts')).toBe('lodash');
    expect(packageRoot('@scope/pkg/sub/path', 'ts')).toBe('@scope/pkg');
    expect(packageRoot('node:fs/promises', 'ts')).toBe('fs');
    expect(packageRoot('react', 'tsx')).toBe('react');
  });

  it('uses the right separator for each ecosystem', () => {
    expect(packageRoot('django.db.models', 'py')).toBe('django');
    expect(packageRoot('serde::de::Error', 'rs')).toBe('serde');
    expect(packageRoot('github.com/gin-gonic/gin/binding', 'go')).toBe('github.com/gin-gonic/gin');
    expect(packageRoot('net/http', 'go')).toBe('net');
    expect(packageRoot('com.example.Thing', 'java')).toBe('com');
    expect(packageRoot('App\\Models\\User', 'php')).toBe('App');
  });

  it('returns an empty string for an empty specifier', () => {
    expect(packageRoot('   ', 'ts')).toBe('');
  });
});
