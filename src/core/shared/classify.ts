/**
 * File-role classification.
 *
 * Several analyzers need to agree on "is this a test?" or "is this generated?".
 * Centralising the predicates keeps the health score, the graph and the stats
 * from disagreeing with each other.
 */

import { basename, isUnder } from './paths';
import { detectLanguage, extensionOf } from './languages';

const TEST_DIR_NAMES = new Set([
  'test',
  'tests',
  '__tests__',
  'spec',
  'specs',
  'e2e',
  'cypress',
  'playwright',
  'testing',
  'integration-tests',
]);

const TEST_FILE_PATTERN = /\.(test|spec)\.[cm]?[jt]sx?$/i;
const PY_TEST_PATTERN = /(^|\/)(test_[^/]+\.py|[^/]+_test\.py)$/i;
const GO_TEST_PATTERN = /_test\.go$/i;
const RS_TEST_PATTERN = /(^|\/)tests\/[^/]+\.rs$/i;
const RB_TEST_PATTERN = /(_spec|_test)\.rb$/i;
const JAVA_TEST_PATTERN = /(Test|Tests|IT)\.(java|kt|scala)$/;

/** True for unit, integration or end-to-end test files across ecosystems. */
export function isTestFile(path: string): boolean {
  if (TEST_FILE_PATTERN.test(path)) return true;
  if (PY_TEST_PATTERN.test(path)) return true;
  if (GO_TEST_PATTERN.test(path)) return true;
  if (RS_TEST_PATTERN.test(path)) return true;
  if (RB_TEST_PATTERN.test(path)) return true;
  if (JAVA_TEST_PATTERN.test(path)) return true;

  return path.split('/').some((segment) => TEST_DIR_NAMES.has(segment.toLowerCase()));
}

