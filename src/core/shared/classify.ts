const CONFIG_EXTENSIONS = new Set(['toml', 'ini', 'cfg', 'conf', 'properties']);

/** True for build, tooling, dependency and deployment configuration. */
export function isConfigFile(path: string): boolean {
  const base = basename(path).toLowerCase();

  if (CONFIG_BASENAMES.has(base)) return true;
  if (base.startsWith('.env')) return true;
  if (/^\.[a-z]+rc(\.[a-z]+)?$/.test(base)) return true;
  if (/\.config\.[cm]?[jt]s$/.test(base)) return true;
  if (CONFIG_EXTENSIONS.has(extensionOf(path))) return true;
  if (isUnder(path, '.github')) return true;
  if (isUnder(path, '.circleci')) return true;

  return false;
}

const DOC_EXTENSIONS = new Set(['md', 'mdx', 'rst', 'adoc', 'txt']);
const DOC_DIRS = new Set(['docs', 'doc', 'documentation', 'wiki', 'guides']);

/** True for prose documentation, including top-level community health files. */
export function isDocumentationFile(path: string): boolean {
  if (DOC_EXTENSIONS.has(extensionOf(path))) return true;
  const first = path.split('/')[0]?.toLowerCase() ?? '';
  return DOC_DIRS.has(first);
}

const GENERATED_PATTERNS: readonly RegExp[] = [
  /(^|\/)(dist|build|out|target|bin|obj|coverage|\.next|\.nuxt|\.svelte-kit|\.turbo)\//,
  /\.min\.(js|css)$/,
  /\.bundle\.js$/,
  /\.d\.ts$/,
  /(^|\/)generated\//,
  /(^|\/)__generated__\//,
  /\.pb\.(go|ts|js|py)$/,
  /_pb2\.py$/,
];

const GENERATED_HEADER =
  /^(\/\/|#|\/\*|<!--)?\s*(@generated|Code generated by|DO NOT EDIT|AUTO-GENERATED)/im;

/**
 * True for machine-generated code.
 *
 * Checks the path first, then the first few lines for a generation banner —
 * the convention most codegen tools follow.
 */
export function isGeneratedFile(path: string, content?: string | null): boolean {
  if (GENERATED_PATTERNS.some((pattern) => pattern.test(path))) return true;
  if (!content) return false;
  return GENERATED_HEADER.test(content.slice(0, 500));
}

/** True for vendored third-party code that should not count against the repo. */
export function isVendored(path: string): boolean {
  return /(^|\/)(vendor|vendors|third_party|thirdparty|node_modules|bower_components)\//.test(path);
}

/**
 * A "source file" for statistics: real, hand-written program code.
 * Excludes tests, generated output and vendored trees.
 */
export function isCountableSource(path: string, content?: string | null): boolean {
  if (!detectLanguage(path).isSource) return false;
  if (isVendored(path)) return false;
  if (isGeneratedFile(path, content)) return false;
  return true;
}
