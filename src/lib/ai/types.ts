/**
 * The reasoning provider interface.
 *
 * GitBrain has two implementations behind this one interface:
 *
 *   - `LocalReasoner` — retrieval over the real analysis, with no network call
 *     and no cost. Always available.
 *   - `OpenRouterProvider` — an LLM, used when `OPENROUTER_API_KEY` is set.
 *
 * Both stream. Both cite real files. The UI cannot tell them apart structurally,
 * which is what makes "works with zero configuration" a real promise rather
 * than a degraded demo mode.
 */

import type { Analysis, Citation } from '@/core/types';

export interface ReasoningRequest {
  /** The user's question. */
  readonly question: string;
  /** Prior turns, oldest first. Providers may truncate to fit a context budget. */
  readonly history: readonly { readonly role: 'user' | 'assistant'; readonly content: string }[];
  /** The analysis being discussed. */
  readonly analysis: Analysis;
  readonly signal?: AbortSignal;
}

/**
 * A streamed chunk.
 *
 * `citations` arrives once, before or alongside the first text, so the UI can
 * render source chips immediately instead of waiting for generation to finish.
 */
export type ReasoningChunk =
  | { readonly type: 'citations'; readonly citations: readonly Citation[] }
  | { readonly type: 'text'; readonly text: string }
  | { readonly type: 'error'; readonly message: string }
  | { readonly type: 'done' };

export interface ReasoningProvider {
  /** Stable identifier surfaced in the UI, e.g. `local` or a model slug. */
  readonly id: string;
  /** Human-readable name shown next to answers. */
  readonly label: string;
  /** True when answers are generated by a language model. */
  readonly isGenerative: boolean;

  answer(request: ReasoningRequest): AsyncIterable<ReasoningChunk>;
}
